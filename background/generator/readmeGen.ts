function buildHeader(toolSetName: string, intro: string): string {
  return `# ${toolSetName} MCP Server

> Generated by [YOSO](https://github.com/YosoMCP/yoso-extension) — You Only Show Once

${intro}`
}

function buildToolsSection(branches: Branch[]): string {
  const registered = branches.filter(b => b.registration)
  if (registered.length === 0) return `## Tools\n\n_No tools registered yet._`

  const toolDocs = registered.map(b => buildToolDoc(b)).join('\n\n')
  return `## Tools\n\n${toolDocs}`
}

function buildToolDoc(branch: Branch): string {
  const reg = branch.registration!
  const lines: string[] = []
  const behavior = summarizeToolBehavior(branch)

  lines.push(`### \`${reg.toolName}\``)
  lines.push('')
  lines.push(reg.toolDescription)
  lines.push('')
  lines.push(`**Applicable scenario:** ${behavior.usageScenario}`)
  lines.push('')
  lines.push('**Side effects:**')
  for (const effect of behavior.sideEffects) {
    lines.push(`- ${effect}`)
  }

  if (branch.params.length > 0) {
    lines.push('')
    lines.push('**Parameters:**')
    lines.push('')
    lines.push('| Name | Type | Required | Default | Description | Enum |')
    lines.push('|------|------|----------|---------|-------------|------|')
    for (const p of branch.params) {
      const name = resolveRegisteredParamName(p, reg)
      const desc = resolveParamBusinessDescription(p)
      const opts = p.enumOptions ? p.enumOptions.map(o => `\`${o}\``).join(', ') : '—'
      const required = isSchemaParamRequired(p) ? 'Yes' : 'No'
      const defaultValue = formatDefaultValue(p.defaultValue)
      lines.push(`| \`${name}\` | \`${p.type}\` | ${required} | ${defaultValue} | ${desc} | ${opts} |`)
    }
  }

  if (branch.returns.length > 0) {
    lines.push('')
    lines.push('**Returns:**')
    for (const r of branch.returns) {
      if (r.extractMode === 'screenshot') {
        lines.push(`- Screenshot saved to \`extract-{timestamp}.png\``)
      } else {
        lines.push(`- Text content from \`${r.selector.slice(0, 60)}${r.selector.length > 60 ? '…' : ''}\``)
      }
    }
  }

  return lines.join('\n')
}

function formatDefaultValue(value: unknown): string {
  if (value === undefined || value === null) return '—'
  if (typeof value === 'string') return `\`${value}\``
  if (typeof value === 'number' || typeof value === 'boolean') return `\`${String(value)}\``
  return `\`${JSON.stringify(value)}\``
}

function buildServerBoundary(): string {
  return `## Server Boundary

### This server does

- Executes validated browser workflows that were recorded in YOSO.
- Exposes each workflow as an MCP tool with typed input schema.
- Runs browser automation through Playwright in a real Chromium session.

### This server does not

- Does not bypass login requirements, captcha, or target platform security checks.
- Does not guarantee workflow stability when website layout or business flow changes.
- Does not support concurrent tool calls in a single server process.`
}


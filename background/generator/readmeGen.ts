function toKebabCase(name: string): string {
  return name
    .toLowerCase()
    .replace(/[\u4e00-\u9fa5]+/g, s => s) // keep Chinese as-is
    .replace(/[^a-z0-9\u4e00-\u9fa5]+/g, '-')
    .replace(/^-+|-+$/g, '')
    || 'mcp-server'
}

function buildErrorSemantics(): string {
  return `## Error Semantics

| Error code | Retryable | Meaning | Recommended recovery |
|------------|-----------|---------|----------------------|
| \`RETRYABLE_TIMEOUT\` | Yes | Temporary timeout while waiting for page/UI readiness | Retry the same tool call |
| \`NON_RETRYABLE_AUTH_REQUIRED\` | No | Authentication state is missing or expired | Re-login, then call again |
| \`NON_RETRYABLE_SELECTOR_STALE\` | No | Recorded selector no longer matches current UI | Re-record workflow in YOSO |
| \`NON_RETRYABLE_INVALID_ARGUMENT\` | No | Arguments do not satisfy expected semantics | Correct arguments or re-record |
| \`NON_RETRYABLE_UNKNOWN_TOOL\` | No | Tool name does not exist in current server | Refresh tool list or re-export |
| \`NON_RETRYABLE_UNKNOWN\` | No | Unclassified execution failure | Inspect payload, then re-record if persistent |`
}

function buildRuntimeAndState(branches: Branch[]): string {
  const needsSession = branchesHaveWaitNodes(branches)
  return `## Runtime & State

- **Login/session source:** ${needsSession ? 'Session Broker (persisted Playwright storage state under user home).' : 'No Session Broker persistence is required for this export.'}
- **Timeout behavior:** wait steps use staged timeout recovery (short wait first, then extended wait for manual completion).
- **Concurrency:** one tool call at a time in a single process; avoid parallel invocations.
- **Browser lifecycle:** each tool call closes browser context at the end of execution.`
}


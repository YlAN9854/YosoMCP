function buildTroubleshooting(): string {
  return `## Troubleshooting

| Problem | Solution |
|---------|----------|
| \`Cannot find module '@modelcontextprotocol/sdk'\` | Run \`npm install @modelcontextprotocol/sdk playwright\` in the server folder |
| \`browserType.launch: Executable doesn't exist\` | Run \`npx playwright install chromium\` |
| \`tsx: command not found\` | Run \`npm install -D tsx\` then use \`npx tsx\` |
| \`Top-level await is not supported with the "cjs" output format\` | Add \`"type": "module"\` to your \`package.json\`, or upgrade to \`tsx\` ≥ 4: \`npm install -D tsx@latest\` |
| Server not appearing in MCP client | Verify the absolute path in the config is correct; check the client's MCP logs for errors |
| Browser opens but actions fail | The target website may have changed its layout — re-record in YOSO |
| Timeout errors on slow pages | Increase the \`ACTION_DELAY\` constant at the top of the server file |`
}


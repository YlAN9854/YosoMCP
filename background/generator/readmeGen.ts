export async function generateReadme(
  branches: Branch[],
  toolSetName: string,
  serverFileName: string,
  llmSettings?: LLMSettings,
): Promise<string> {
  const registeredBranches = branches.filter(b => b.registration)

  // Build a brief tool list for LLM context
  const toolListText = registeredBranches
    .map(b => `- ${b.registration!.toolName}: ${b.registration!.toolDescription}`)
    .join('\n')

  // Attempt LLM-enhanced introduction (graceful fallback on any failure)
  let intro = ''
  if (llmSettings?.apiKey && registeredBranches.length > 0) {
    try {
      intro = await generateLLMIntro(toolSetName, toolListText, llmSettings)
    } catch {
      // silently ignore — template intro used below
    }
  }
  if (!intro) {
    intro = generateTemplateIntro(toolSetName, registeredBranches)
  }

  return buildReadme(branches, toolSetName, serverFileName, intro)
}

// ---------------------------------------------------------------------------
// LLM intro generation
// ---------------------------------------------------------------------------

async function generateLLMIntro(
  toolSetName: string,
  toolListText: string,
  settings: LLMSettings,
): Promise<string> {
  const systemPrompt = `You are a technical documentation writer. Your task is to write concise, clear introductions for MCP (Model Context Protocol) server README files. Write in English. Be direct and informative. Do NOT include headings, bullet points, or markdown — return plain text only (2-4 sentences).`

  const userPrompt = `Write a concise introduction for a MCP server named "${toolSetName}".

Available tools:
${toolListText}

The introduction should explain:
1. What this MCP server enables users to do
2. The main automation capabilities it provides

Return plain text only, no markdown formatting.`

  const raw = await callLLM(settings, systemPrompt, userPrompt)
  // Strip any accidental markdown headings or fences
  return raw
    .replace(/^#+\s+.*/gm, '')
    .replace(/```[\s\S]*?```/g, '')
    .trim()
}

function generateTemplateIntro(toolSetName: string, branches: Branch[]): string {
  if (branches.length === 0) {
    return `This MCP server provides browser automation tools generated by YOSO. It uses Playwright to control a Chromium browser and exposes each recorded workflow as an MCP-compatible tool.`
  }

  const toolNames = branches
    .filter(b => b.registration)
    .map(b => `\`${b.registration!.toolName}\``)
    .slice(0, 4)
    .join(', ')

  const more = branches.length > 4 ? ` and ${branches.length - 4} more` : ''
  return `This MCP server provides browser automation for **${toolSetName}**, generated by [YOSO](https://github.com/YosoMCP/yoso-extension). It exposes ${branches.length} tool${branches.length !== 1 ? 's' : ''} — ${toolNames}${more} — letting any MCP-compatible AI client interact with a real browser to automate your workflows.`
}

// ---------------------------------------------------------------------------
// README assembly
// ---------------------------------------------------------------------------

function buildReadme(
  branches: Branch[],
  toolSetName: string,
  serverFileName: string,
  intro: string,
): string {
  const serverName = toKebabCase(toolSetName)
  const sections: string[] = []

  sections.push(buildHeader(toolSetName, intro))
  sections.push(buildServerBoundary())
  sections.push(buildToolsSection(branches))
  sections.push(buildReturnContract(serverName))
  sections.push(buildErrorSemantics())
  sections.push(buildRuntimeAndState(branches))
  sections.push(buildPrerequisites())
  sections.push(buildInstallation(serverFileName))
  sections.push(buildMCPConfig(serverName, serverFileName))
  sections.push(buildTroubleshooting())
  sections.push(buildFooter())

  return sections.join('\n\n---\n\n')
}

// ---------------------------------------------------------------------------
// Section builders
